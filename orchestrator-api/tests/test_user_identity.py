def test_identity_migration_preserves_existing_account_session_and_unknown_dates(postgres_dsn):
    schema = 'identity_upgrade_' + uuid4().hex
    migrations = Path(__file__).resolve().parents[1] / 'app' / 'migrations'
    with psycopg.connect(postgres_dsn, autocommit=True, row_factory=dict_row) as connection:
        connection.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(schema)))
        try:
            connection.execute(sql.SQL('SET search_path TO {}').format(sql.Identifier(schema)))
            for migration in sorted(migrations.glob('*.sql')):
                if migration.name < '011_user_identity.sql':
                    connection.execute(migration.read_text())
            user_id = uuid4()
            connection.execute(
                "INSERT INTO auth_users(id,username,display_name,password_hash,role) VALUES(%s,'existing-admin','Original Admin','unchanged-hash','admin')",
                (user_id,),
            )
            connection.execute("INSERT INTO auth_sessions(token_hash,user_id,expires_at) VALUES('existing-session',%s,now()+interval '1 hour')", (user_id,))
            connection.execute((migrations / '011_user_identity.sql').read_text())
            user = connection.execute('SELECT * FROM auth_users WHERE id=%s', (user_id,)).fetchone()
            assert user['display_name'] == 'Original Admin' and user['password_hash'] == 'unchanged-hash'
            assert user['first_name'] == user['last_name'] == '' and user['email'] is None
            assert user['last_login_at'] is None and user['password_changed_at'] is None
            assert connection.execute('SELECT token_hash FROM auth_sessions').fetchone()['token_hash'] == 'existing-session'
            fresh = connection.execute("INSERT INTO auth_users(id,username,display_name,password_hash) VALUES(%s,'fresh-admin','Fresh','hash') RETURNING password_changed_at", (uuid4(),)).fetchone()
            assert fresh['password_changed_at'] is not None
        finally:
            connection.execute(sql.SQL('DROP SCHEMA {} CASCADE').format(sql.Identifier(schema)))


def test_unicode_identity_autogenerated_login_and_email_canonicalization(auth_store, app_module):
    _, client, _ = signed_in(auth_store, app_module)
    result = client.post('/console/users', json={
        'first_name': '  Élodie   Marie ', 'last_name': " D’Arcy   李 ",
        'email': ' Élodie@EXAMPLE.COM ', 'role': 'builder',
    })
    assert result.status_code == 201, result.text
    user = result.json()['user']
    assert user['first_name'] == 'Élodie Marie' and user['last_name'] == 'D’Arcy 李'
    assert user['display_name'] == 'Élodie Marie D’Arcy 李'
    assert user['username'] == 'elodie-marie.darcy'
    assert user['email'] == 'Élodie@example.com'
    assert user['active_sessions'] == user['recovery_codes_remaining'] == 0
    assert user['last_login_at'] is None and user['password_changed_at'] is not None
    duplicate = client.post('/console/users', json={'first_name': 'Other', 'email': 'élodie@Example.Com', 'role': 'viewer'})
    assert duplicate.status_code == 409 and duplicate.json() == {'detail': {'code': 'email_in_use'}}
    maximum = client.post('/console/users', json={'first_name': 'É' * 120, 'last_name': '李' * 120, 'role': 'viewer'})
    assert maximum.status_code == 201 and len(maximum.json()['user']['display_name']) == 241
    mononym = client.post('/console/users', json={'first_name': '李', 'role': 'viewer'})
    assert mononym.status_code == 201 and mononym.json()['user']['display_name'] == '李'


def test_concurrent_automatic_logins_resolve_collisions_and_email_stays_unique(auth_store, app_module):
    _, client, _ = signed_in(auth_store, app_module)
    with ThreadPoolExecutor(max_workers=2) as pool:
        responses = list(pool.map(lambda n: client.post('/console/users', json={
            'first_name': 'Jean', 'last_name': 'Dupont', 'email': f'jean{n}@example.com', 'role': 'builder',
        }), [1, 2]))
    assert [response.status_code for response in responses] == [201, 201]
    assert {response.json()['user']['username'] for response in responses} == {'jean.dupont', 'jean.dupont-2'}
    with ThreadPoolExecutor(max_workers=2) as pool:
        responses = list(pool.map(lambda n: client.post('/console/users', json={
            'first_name': f'Concurrent {n}', 'email': 'same-contact@example.com', 'role': 'viewer',
        }), [1, 2]))
    assert sorted(response.status_code for response in responses) == [201, 409]
    assert next(response for response in responses if response.status_code == 409).json()['detail']['code'] == 'email_in_use'


def test_validation_never_echoes_contact_input_and_clearing_preserves_legacy_identity(auth_store, app_module):
    user, client, _ = signed_in(auth_store, app_module)
    for email in ['private-contact-without-domain', 'private\x00@example.com', '\ud800@example.com']:
        response = client.post('/console/users', content=json.dumps({'first_name': 'Person', 'email': email, 'role': 'viewer'}), headers={'Content-Type': 'application/json'})
        assert response.status_code == 422 and response.json() == {'detail': {'code': 'invalid_email'}}
        assert 'private' not in response.text
    for name in ['\x00Private', '\ud800', '!!!']:
        response = client.post('/console/users', content=json.dumps({'first_name': name, 'role': 'viewer'}), headers={'Content-Type': 'application/json'})
        assert response.status_code == 422 and 'Private' not in response.text
    changed = client.patch(f"/console/users/{user['id']}", json={'email': 'private-admin@example.com'})
    assert changed.status_code == 200
    assert changed.json()['display_name'] == user['display_name']
    assert changed.json()['first_name'] == changed.json()['last_name'] == ''
    assert client.patch(f"/console/users/{user['id']}", json={'email': None}).json()['email'] is None
    assert client.patch(f"/console/users/{user['id']}", json={}).status_code == 422
    assert client.patch(f"/console/users/{user['id']}", json={'username': 'renamed'}).status_code == 422
    with auth_store.connect() as connection:
        assert 'private-admin@example.com' not in str(connection.execute('SELECT * FROM audit_log').fetchall())


def test_directory_search_filters_and_details_apply_across_all_pages(auth_store, app_module):
    _, admin, _ = signed_in(auth_store, app_module)
    ready_user, _, _ = signed_in(auth_store, app_module, 'operator')
    pending = admin.post('/console/users', json={'username': 'zzz-contact', 'first_name': 'Unique', 'last_name': 'Person', 'email': 'find-me@example.com', 'role': 'builder'}).json()['user']
    with auth_store.connect() as connection:
        password_hash = connection.execute('SELECT password_hash FROM auth_users LIMIT 1').fetchone()['password_hash']
        for number in range(55):
            connection.execute('INSERT INTO auth_users(id,username,display_name,role,password_hash) VALUES(%s,%s,%s,\'viewer\',%s)',
                               (uuid4(), f'filler-{number:02}', f'Filler {number}', password_hash))
        connection.execute("INSERT INTO auth_sessions(token_hash,user_id,expires_at) VALUES('expired-session',%s,now()-interval '1 hour')", (ready_user['id'],))
    first_page = admin.get('/console/users', params={'limit': 50}).json()
    assert first_page['total'] == 58 and pending['id'] not in {item['id'] for item in first_page['items']}
    searched = admin.get('/console/users', params={'q': 'FIND-ME@EXAMPLE.COM', 'limit': 1}).json()
    assert searched['total'] == 1 and searched['items'][0]['id'] == pending['id']
    assert admin.get('/console/users', params={'q': 'Unique Person', 'offset': 1}).json()['total'] == 1
    filtered = admin.get('/console/users', params={'role': 'builder', 'two_factor': 'pending', 'onboarding': 'required', 'active': 'active'}).json()
    assert filtered['total'] == 1 and filtered['items'][0]['id'] == pending['id']
    assert admin.get('/console/users', params={'two_factor': 'enabled', 'onboarding': 'ready'}).json()['total'] == 2
    assert admin.patch(f"/console/users/{pending['id']}", json={'active': False}).status_code == 200
    assert admin.get('/console/users', params={'active': 'inactive'}).json()['items'][0]['id'] == pending['id']
    details = admin.get(f"/console/users/{ready_user['id']}")
    assert details.status_code == 200
    assert details.json()['active_sessions'] == 1 and details.json()['recovery_codes_remaining'] == 10
    assert details.json()['last_login_at'] is not None
    for secret in ['password_hash', 'totp_secret', 'code_hash', 'token_hash', 'expired-session']:
        assert secret not in details.text
    assert admin.get(f'/console/users/{uuid4()}').status_code == 404
    assert admin.get('/console/users', params={'role': 'root'}).status_code == 422
    assert admin.get('/console/users', params={'q': 'x' * 320}).status_code == 200
    assert admin.get('/console/users', params={'q': 'x' * 321}).status_code == 422
    assert admin.get('/console/users', params={'q': '\x00'}).status_code == 422


def test_pending_admin_cannot_replace_the_last_ready_admin(auth_store, app_module):
    ready, client, _ = signed_in(auth_store, app_module)
    pending = client.post('/console/users', json={'username': 'pending-admin', 'role': 'admin'}).json()['user']
    for changes in [{'role': 'viewer'}, {'active': False}]:
        response = client.patch(f"/console/users/{ready['id']}", json=changes)
